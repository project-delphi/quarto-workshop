"""Write the HTML and EPUB profiles' chapter lists from _chapters.yml.

Quarto 1.10.20 drops `part:` entries from EPUB, and a profile's `book.chapters` is
appended to the base list rather than replacing it (book/PLAN.md, findings S1 and S2).
So the base _quarto.yml has no chapter list, and this script writes one per profile:

- _quarto-html.yml: chapters grouped under `part:` pages, for the HTML sidebar;
- _quarto-epub.yml: one flat list in which the part pages are ordinary chapters
  (scripts/epub_postprocess.py nests the EPUB table of contents under them).

Run from book/:  uv run python scripts/sync_chapters.py [--check]
--check exits with status 1 if a profile on disk differs from what it would write.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

BOOK = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/sync_chapters.py from _chapters.yml: do not edit.\n"


def profiles(spec: dict) -> dict[str, dict]:
    grouped = [*spec["front"]]
    flat = [*spec["front"]]
    for part in spec["parts"]:
        grouped.append({"part": part["file"], "chapters": part["chapters"]})
        flat += [part["file"], *part["chapters"]]
    grouped += spec["back"]
    flat += spec["back"]
    return {
        "html": {"project": {"output-dir": "_book/html"},
                 "book": {"chapters": grouped, "appendices": spec["appendices"]}},
        "epub": {"project": {"output-dir": "_book/epub"},
                 "book": {"chapters": flat, "appendices": spec["appendices"]}},
    }


def main() -> int:
    spec = yaml.safe_load((BOOK / "_chapters.yml").read_text())
    check = "--check" in sys.argv[1:]
    stale = []
    for name, data in profiles(spec).items():
        path = BOOK / f"_quarto-{name}.yml"
        text = HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
        if path.exists() and path.read_text() == text:
            continue
        if check:
            stale.append(path.name)
        else:
            path.write_text(text)
            print(f"wrote {path.name}")
    if stale:
        print("stale (run scripts/sync_chapters.py):", ", ".join(stale), file=sys.stderr)
        return 1
    missing = [f for f in [*spec["front"], *spec["back"], *spec["appendices"],
                           *(p["file"] for p in spec["parts"]),
                           *(c for p in spec["parts"] for c in p["chapters"])]
               if not (BOOK / f).exists()]
    if missing:
        print("missing chapter files:", ", ".join(missing), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
