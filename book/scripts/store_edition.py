"""Make the store edition of a published EPUB, for Apple Books and Google Play Books
(book/STORES.md), with its cover and a listing sheet:

    uv run python scripts/store_edition.py ../docs/book/prompt-check-publish.epub _book/store/en

Apple Books takes only JPEG and PNG images inside a book, and Google Play Books only static
GIFs, so each animated GIF becomes a PNG of its first frame. That frame is the GIF's still by
design (book/README.md: every GIF opens on a finished frame, which e-readers that do not
animate show), and it must match the GIF's committed still in media/stills/ (make media), or the
script stops. Each such image's alt text gains "Still from an animation:" in front, since the
reader sees one frame. Nothing else changes.

It writes into OUT: the EPUB (named *-store.epub), cover.png (the edition's 1600 x 2560
cover, which both stores accept) and listing.md, the fields both stores ask for, read from
the EPUB's own metadata and AI usage statement. Validate the EPUB with EPUBCheck after
(make book-store does).
"""
from __future__ import annotations

import html
import io
import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parents[1]  # book/
STILLS = HERE / "media/stills"
ROOT = HERE.parent

# BISAC subjects, from BISG's COMPUTERS list (https://bisg.org/computers, checked 2026-11-16).
SUBJECTS = [("COM089000", "COMPUTERS / Data Visualization"),
            ("COM004000", "COMPUTERS / Artificial Intelligence / General")]

WORDS = {
    "en": {"marker": "AI usage statement.", "cover": ROOT / "book/media/cover.png",
           "disclosure": "AI disclosure: ", "still": "Still from an animation: "},
    "es": {"marker": "Declaración de uso de IA.", "cover": ROOT / "book-es/media/cover.png",
           "disclosure": "Declaración de IA: ", "still": "Fotograma de una animación: "},
}


def text(fragment: str) -> str:
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", fragment))).strip()


def first_frames(z: zipfile.ZipFile, names: list[str]) -> dict[str, bytes]:
    """Each GIF's first frame as PNG bytes, keyed by the GIF's path in the zip; each must match
    one of the book's committed stills (mean difference under 2 of 255), or the script stops."""
    stills = [np.asarray(Image.open(f).convert("RGB"), dtype=float) for f in sorted(STILLS.glob("*.png"))]
    out = {}
    for n in names:
        if not n.lower().endswith(".gif"):
            continue
        with Image.open(io.BytesIO(z.read(n))) as im:
            im.seek(0)
            frame = im.convert("RGB")
        a = np.asarray(frame, dtype=float)
        if not any(s.shape == a.shape and np.abs(s - a).mean() < 2 for s in stills):
            sys.exit(f"store_edition: {n}'s first frame matches no still in {STILLS}; run make media")
        buf = io.BytesIO()
        frame.save(buf, "PNG", optimize=True)
        out[n] = buf.getvalue()
    return out


def listing(opf: str, pages: dict[str, str], lang: str, epub_name: str) -> str:
    """The listing sheet's text; stops, naming the field, if the EPUB lacks one."""
    w = WORDS[lang]

    def dc(tag: str) -> list[str]:
        found = [text(m) for m in re.findall(rf"<dc:{tag}\b[^>]*>(.*?)</dc:{tag}>", opf, re.S)]
        if not found:
            sys.exit(f"store_edition: the EPUB has no dc:{tag}")
        return found
    titles, desc = dc("title"), dc("description")[0]
    if re.search(r"\b(free|gratis|gratuito)\b", desc, re.I):
        sys.exit("store_edition: the description mentions the price; Apple Books rejects that")
    statement = ""
    for body in pages.values():
        m = re.search(r"<p>\s*<strong>" + re.escape(w["marker"]) + r"</strong>(.*?)</p>", body, re.S)
        if m:
            statement = text(m.group(1))
            break
    if not statement:
        sys.exit(f"store_edition: no '{w['marker']}' paragraph in the EPUB")
    return "\n".join([
        f"# Store listing: {titles[0]} ({lang})",
        "",
        "Generated by book/scripts/store_edition.py from the EPUB's metadata; copy each field",
        "into Apple Books or Google Play Books (book/STORES.md says where).",
        "",
        f"- **Book file:** {epub_name}",
        "- **Cover:** cover.png (1600 x 2560 PNG)",
        f"- **Title:** {titles[0]}",
        f"- **Subtitle:** {titles[1] if len(titles) > 1 else ''}",
        f"- **Author:** {dc('creator')[0]}",
        f"- **Publisher:** {dc('publisher')[0]}",
        f"- **Language:** {dc('language')[0]}",
        f"- **Publication date:** {dc('date')[0]}",
        "- **Price:** 0 (free) in every country",
        f"- **Apple Vendor ID:** prompt-check-publish-{lang} (no ISBN; Google assigns a GGKEY)",
        "- **Subjects (BISAC):** " + "; ".join(f"{c} {n}" for c, n in SUBJECTS),
        "",
        "## Description",
        "",
        "Paste both paragraphs: Apple Books asks for the AI disclosure in the description.",
        "",
        desc,
        "",
        w["disclosure"] + statement,
        "",
    ])


def main(src: Path, out: Path) -> None:
    with zipfile.ZipFile(src) as z:
        names = z.namelist()
        files = {n: z.read(n) for n in names}
        frames = first_frames(z, names)
    renamed = {n: n[:-4] + ".png" for n in frames}
    clash = set(renamed.values()) & set(names)
    if clash:
        sys.exit(f"store_edition: {sorted(clash)} already exist")
    # References are relative (../media/file7.gif in pages, media/file7.gif in the OPF): rewrite
    # only src and href values that end in a converted GIF's file name.
    swap = {Path(n).name: Path(p).name for n, p in renamed.items()}
    ref = re.compile(r'((?:src|href)="[^"]*/)([^"/]+\.gif)"')
    opf_name = next(n for n in names if n.endswith(".opf"))
    opf = files[opf_name].decode("utf-8")
    lang = "es" if re.search(r"<dc:language\b[^>]*>\s*es", opf) else "en"
    still = WORDS[lang]["still"]

    def fix_refs(s: str) -> str:
        return ref.sub(lambda m: m.group(1) + swap.get(m.group(2), m.group(2)) + '"', s)

    def fix_alt(img: re.Match) -> str:
        tag = img.group(0)
        if not re.search(r'src="[^"]*/(?:' + "|".join(map(re.escape, swap.values())) + ')"', tag):
            return tag
        return re.sub(r'alt="', 'alt="' + html.escape(still), tag, count=1)

    pages = {}
    for n in names:
        if n.endswith(".xhtml"):
            s = fix_refs(files[n].decode("utf-8"))
            if swap:
                s = re.sub(r"<img\b[^>]*>", fix_alt, s)
            pages[n] = s
            files[n] = s.encode("utf-8")
    opf = fix_refs(opf)
    opf = re.sub(r'(<item\b[^>]*href="[^"]+\.png"[^>]*media-type=")image/gif"', r'\1image/png"', opf)
    if "image/gif" in opf:
        sys.exit("store_edition: the OPF still lists a GIF")
    files[opf_name] = opf.encode("utf-8")

    dest_name = src.name.replace(".epub", "-store.epub")
    sheet = listing(opf, pages, lang, dest_name)  # stops before writing anything if a field is missing
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=out, suffix=".epub", delete=False) as tmp:
        with zipfile.ZipFile(tmp, "w") as o:
            o.writestr(zipfile.ZipInfo("mimetype"), files["mimetype"], zipfile.ZIP_STORED)
            for n in names:
                if n == "mimetype":
                    continue
                if n in frames:
                    o.writestr(renamed[n], frames[n], zipfile.ZIP_DEFLATED)
                else:
                    o.writestr(n, files[n], zipfile.ZIP_DEFLATED)
    dest = out / dest_name
    Path(tmp.name).replace(dest)
    shutil.copyfile(WORDS[lang]["cover"], out / "cover.png")
    (out / "listing.md").write_text(sheet)
    print(f"store_edition: {dest} ({len(frames)} GIFs made stills, "
          f"{dest.stat().st_size / 1e6:.1f} MB), cover.png, listing.md")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), Path(sys.argv[2]))
